"""The conditions summary both apps display.

Until now this data had exactly one consumer: the triage prompt. The console
received the raw `environment` JSON and never rendered it, and the reporter app
never received it at all -- so the person standing on the beach and the
coordinator deciding whether to send a team could both see the agent's
*conclusion* ("tide is rising, high water in 3h") without the reading behind
it.

Built in one place, and served on both the responder detail and the reporter's
turn, so the two cannot drift into describing the same incident differently.

Every field is optional. A failed API call shows as a gap, never as a
comfortable default -- `unavailable` names what is missing so a client can say
"tide unknown" rather than implying calm water.
"""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, Field

from lifejacket.context.tides import describe_tide
from lifejacket.context.weather import minutes_to_sunset
from lifejacket.models.schemas import EnvironmentalContext


class ConditionsOut(BaseModel):
    """Weather, tide, and daylight at the incident, for display."""

    place_name: str | None = None
    local_time: datetime | None = None

    temperature_c: float | None = None
    wind_speed_mph: float | None = None
    wind_gust_mph: float | None = None
    #: Falling now, in mm. Distinct from the probability below.
    precipitation_mm: float | None = None
    precipitation_probability: float | None = None
    visibility_miles: float | None = None
    condition: str | None = None

    #: 0 means it is already dark; null means sunset is unknown. These are not
    #: the same thing and clients must not render them the same way.
    minutes_to_sunset: int | None = None
    sunset_local: datetime | None = None

    tide_trend: str | None = None
    #: One sentence a responder can act on, e.g. "Tide is RISING, high water
    #: in about 4h 52m." Generated by the same helper the prompt uses.
    tide_summary: str | None = None
    water_level_m: float | None = None
    wave_height_m: float | None = None
    sea_temperature_c: float | None = None
    tide_station_name: str | None = None
    next_high_tide: datetime | None = None
    next_low_tide: datetime | None = None

    is_coastal: bool = True
    #: Which lookups failed, so a client shows a gap instead of a default.
    unavailable: list[str] = Field(default_factory=list)


def build_conditions(context: EnvironmentalContext | None) -> ConditionsOut | None:
    """Flatten an `EnvironmentalContext` into the display model."""
    if context is None:
        return None

    weather = context.weather
    tide = context.tide

    return ConditionsOut(
        place_name=context.location.place_name if context.location else None,
        local_time=context.local_time,
        temperature_c=weather.temperature_c if weather else None,
        wind_speed_mph=weather.wind_speed_mph if weather else None,
        wind_gust_mph=weather.wind_gust_mph if weather else None,
        precipitation_mm=weather.precipitation_mm if weather else None,
        precipitation_probability=weather.precipitation_probability if weather else None,
        visibility_miles=weather.visibility_miles if weather else None,
        condition=weather.condition if weather else None,
        minutes_to_sunset=minutes_to_sunset(weather, context.local_time),
        sunset_local=weather.sunset_local if weather else None,
        tide_trend=tide.trend if tide else None,
        tide_summary=describe_tide(tide) if tide else None,
        water_level_m=tide.water_level_m if tide else None,
        wave_height_m=tide.wave_height_m if tide else None,
        sea_temperature_c=tide.sea_surface_temperature_c if tide else None,
        tide_station_name=tide.station_name if tide else None,
        next_high_tide=tide.next_high_tide if tide else None,
        next_low_tide=tide.next_low_tide if tide else None,
        is_coastal=context.is_coastal,
        unavailable=list(context.unavailable),
    )


def conditions_from_json(payload: dict | None) -> ConditionsOut | None:
    """Same thing, from the stored `environment_json` column.

    The responder console reads incidents back out of the database, where the
    context lives as JSON rather than as a model.
    """
    if not payload:
        return None
    try:
        return build_conditions(EnvironmentalContext.model_validate(payload))
    except (ValueError, TypeError):
        # A context stored by an older schema version should not take down the
        # detail view; the rest of the incident is still worth showing.
        return None
