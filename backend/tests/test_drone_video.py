def metadata(**changes):
    values = dict(
        evidence_kind="synthetic_test",
        source="Generated test pattern",
        rights_note="Generated by this test; no wildlife evidence",
        recording_started_at="2026-10-29T10:00:00-05:00",
    )
    return VideoMetadata(**(values | changes))


def test_real_decoder_timestamps_hashes_and_review(clip):
    output = clip.parent / "bundle"
    result = prepare_video(clip, output, metadata(), interval=1, max_frames=2)
    assert result["source"]["sha256"] == digest(clip) == digest(output / "source.mp4")
    assert [f["offset_seconds"] for f in result["frames"]] == [0, 1]
    assert result["frames"][1]["captured_at"] == "2026-10-29T10:00:01-05:00"
    assert result["sample_limit_reached"] is True
    assert all(
        f["aircraft_position"] is None and f["animal_position"] is None
        for f in result["frames"]
    )
    assert all(digest(output / f["path"]) == f["sha256"] for f in result["frames"])
    assert json.loads((output / "manifest.json").read_text()) == result
    assert "Not analyzed" in (output / "review.html").read_text()
    with pytest.raises(ValueError, match="already exists"):
        prepare_video(clip, output, metadata())


def test_noninteger_sampling_and_unknown_absolute_time(clip):
    result = prepare_video(
        clip,
        clip.parent / "bundle",
        metadata(recording_started_at=None),
        interval=0.65,
        max_frames=10,
    )
    offsets = [f["offset_seconds"] for f in result["frames"]]
    assert offsets == pytest.approx([0, 0.7, 1.4, 2.1, 2.8])
    assert result["sample_limit_reached"] is False
    assert all(f["captured_at"] is None for f in result["frames"])


@pytest.mark.parametrize(
    "options",
    [
        {"interval": 0},
        {"interval": float("nan")},
        {"interval": 100},
        {"max_frames": 0},
        {"max_frames": 61},
    ],
)
def test_limits_fail_without_partial_output(clip, options):
    output = clip.parent / "bundle"
    with pytest.raises(ValueError):
        prepare_video(clip, output, metadata(), **options)
    assert not output.exists()


def test_corrupt_video_leaves_no_bundle(tmp_path):
    source = tmp_path / "broken.mp4"
    source.write_bytes(b"not a video")
    with pytest.raises(ValueError, match="decoded"):
        prepare_video(source, tmp_path / "bundle", metadata())
    assert not (tmp_path / "bundle").exists()
    assert not list(tmp_path.glob(".video-*"))


def test_metadata_requires_timezone_and_explicit_evidence_kind():
    with pytest.raises(ValidationError):
        metadata(recording_started_at="2026-10-29T10:00:00")
    with pytest.raises(ValidationError):
        metadata(evidence_kind="real_incident")


def test_detection_empty_result_is_distinct_from_failure(clip):
    output = clip.parent / "bundle"
    prepare_video(clip, output, metadata(), max_frames=2)
    client = ScriptedLLMClient().queue("detection", {"animals": []}, LLMCallError("offline"))
    result = detect_frames(output, client=client)
    assert result["manifest_sha256"] == digest(output / "manifest.json")
    assert result["frames"][0]["status"] == "detected"
    assert result["frames"][0]["animals"] == []
    assert result["frames"][1] == {
        "path": "frames/0002.jpg",
        "status": "failed",
        "error_kind": "call_failed",
    }
    assert len(client.calls) == 2
    assert "Detection failed" in (output / "review.html").read_text()
    with pytest.raises(ValueError, match="already exist"):
        detect_frames(output, client=client)


def test_integrity_failure_prevents_all_model_calls(clip):
    output = clip.parent / "bundle"
    prepare_video(clip, output, metadata(), max_frames=2)
    (output / "frames/0002.jpg").write_bytes(b"tampered")
    client = ScriptedLLMClient()
    with pytest.raises(ValueError, match="integrity"):
        detect_frames(output, client=client)
    assert client.calls == []
    assert not (output / "detections.json").exists()


def test_review_escapes_operator_notes(clip):
    output = clip.parent / "bundle"
    prepare_video(clip, output, metadata(source="<script>alert(1)</script>"), max_frames=1)
    review = (output / "review.html").read_text()
    assert "<script>" not in review
    assert "&lt;script&gt;" in review


def test_cli_prepare_runs_without_database_or_credentials(clip):
    meta = clip.parent / "meta.json"
    meta.write_text(metadata().model_dump_json())
    import os

    repo = Path(__file__).resolve().parents[2]
    result = subprocess.run(
        [
            sys.executable,
            "scripts/drone_video.py",
            "prepare",
            str(clip),
            "--metadata",
            str(meta),
            "--output",
            str(clip.parent / "cli"),
            "--max-frames",
            "1",
        ],
        cwd=repo,
        env=os.environ | {"PYTHONPATH": "backend"},
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stderr
    assert "Prepared 1 frames" in result.stdout
