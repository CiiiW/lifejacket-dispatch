def describe_training(run: dict | None) -> str:
    if not run:
        return "_No `run.json` beside the weights, so provenance is unrecorded._"
    rows = [
        ("Started", run.get("started_at", "?")),
        ("Base weights", Path(str(run.get("base_weights", "?"))).name),
        ("Stock DroneMegaDetector base", run.get("base_is_stock_dmd")),
        ("Epochs", run.get("args", {}).get("epochs", "?")),
        ("Learning rate", run.get("args", {}).get("lr", "?")),
        ("Replay dataset", run.get("replay") or "none"),
        ("Replay fraction", run.get("replay_fraction", 0.0)),
        ("Train / valid images", run.get("image_counts", "?")),
        ("Git commit", run.get("git_commit") or "unrecorded"),
    ]
    return "\n".join(f"- **{k}:** `{v}`" for k, v in rows)


def describe_evaluation(metrics: list[tuple[str, dict]]) -> str:
    if not metrics:
        return "_No evaluation files in `results/`. Run `evaluate.py` first._"
    lines = []
    for name, payload in metrics:
        best = payload.get("best", {})
        lines.append(f"### `{name}`\n")
        lines.append(f"Evaluated on {payload.get('images', '?')} images.\n")
        lines.append("| Class | conf | P | R | F1 | blind frames | boxes |")
        lines.append("| --- | --- | --- | --- | --- | --- | --- |")
        for label, row in (payload.get("per_class") or {}).items():
            lines.append(
                f"| {label} | {row.get('confidence')} | {row.get('precision')} | "
                f"{row.get('recall')} | {row.get('f1')} | {row.get('blind_images')} | "
                f"{row.get('ground_truth_boxes', '')} |"
            )
        lines.append(
            f"| **all** | {best.get('confidence')} | {best.get('precision')} | "
            f"{best.get('recall')} | {best.get('f1')} | {best.get('blind_images')} | |"
        )
        if payload.get("regressions"):
            lines.append("\n**Regressions against the baseline:**\n")
            for warning in payload["regressions"]:
                lines.append(f"- {warning}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--weights", type=Path, required=True, help="runs/<name>/checkpoint_best_total.pth"
    )
    parser.add_argument("--repo", required=True, help="Hugging Face repo id, user/name")
    parser.add_argument(
        "--purpose",
        default="a more specific search",
        help="one phrase for the model card, e.g. 'finding hauled-out seals'",
    )
    parser.add_argument("--private", action="store_true")
    parser.add_argument("--message", default="Publish aerial detector")
    parser.add_argument(
        "--tags", help="comma-separated results/eval_*.json stems to include"
    )
    parser.add_argument("--dry-run", action="store_true", help="stage locally, upload nothing")
    parser.add_argument(
        "--allow-class-mismatch",
        action="store_true",
        help="publish anyway. Almost certainly wrong; the app assumes the order",
    )
    args = parser.parse_args()

    if not args.weights.exists():
        raise SystemExit(f"no checkpoint at {args.weights}")

    info = describe_checkpoint(args.weights)
    names = tuple(info.get("class_names") or ())
    print(f"  checkpoint: {info}")
    if names and names != DMD_CLASSES and not args.allow_class_mismatch:
        raise DmdError(
            f"checkpoint classes {list(names)} != {list(DMD_CLASSES)}.\n"
            "backend/lifejacket/drones/detector.py assumes that exact order, so "
            "publishing this would relabel every detection silently. Fix the "
            "fine-tune, or pass --allow-class-mismatch if you know better."
        )
    if not names:
        print("  WARNING: could not read class names from the checkpoint; not verified")

    staging = Path(tempfile.mkdtemp(prefix="aerial-publish-"))
    weights_name = args.weights.name
    shutil.copy2(args.weights, staging / weights_name)

    run_path = args.weights.parent / "run.json"
    if not run_path.exists():
        run_path = args.weights.parent.parent / "run.json"
    run = json.loads(run_path.read_text()) if run_path.exists() else None
    if run:
        shutil.copy2(run_path, staging / "run.json")

    wanted = {t.strip() for t in args.tags.split(",")} if args.tags else None
    metrics: list[tuple[str, dict]] = []
    (staging / "metrics").mkdir()
    for path in sorted(RESULTS.glob("eval_*.json")):
        stem = path.stem.replace("eval_", "")
        if wanted and stem not in wanted:
            continue
        metrics.append((stem, json.loads(path.read_text())))
        shutil.copy2(path, staging / "metrics" / path.name)

    digest = file_sha256(staging / weights_name)
    size_mb = (staging / weights_name).stat().st_size / 1e6
    print(f"  {weights_name}  {size_mb:.1f} MB  sha256 {digest}")

    checkpoint_lines = "\n".join(
        f"- **{key}:** `{value}`" for key, value in info.items() if key != "source"
    )
    card = CARD.format(
        repo=args.repo,
        purpose=args.purpose,
        revision="REVISION_PRINTED_BELOW",
        sha256=digest,
        weights_name=weights_name,
        class_rows="\n".join(f"| {i} | `{n}` |" for i, n in enumerate(DMD_CLASSES)),
        checkpoint=checkpoint_lines,
        training=describe_training(run),
        evaluation=describe_evaluation(metrics),
        generated_at=datetime.now(UTC).isoformat(timespec="seconds"),
    )
    (staging / "README.md").write_text(card)

    if args.dry_run:
        print(f"\n  --dry-run: staged at {staging}, nothing uploaded")
        for path in sorted(staging.rglob("*")):
            if path.is_file():
                print(f"    {path.relative_to(staging)}  {path.stat().st_size / 1e6:.2f} MB")
        print(f"\n  read the card at {staging / 'README.md'} before publishing")
        return 0

    from huggingface_hub import HfApi

    api = HfApi()
    api.create_repo(repo_id=args.repo, private=args.private, exist_ok=True)
    result = api.upload_folder(
        repo_id=args.repo, folder_path=str(staging), commit_message=args.message
    )
    revision = getattr(result, "oid", None) or getattr(result, "commit_id", None)
    if not revision:
        print("  could not read the commit SHA back; take it from the repo history")
        revision = "PASTE_COMMIT_SHA_HERE"

    api.upload_file(
        path_or_fileobj=card.replace("REVISION_PRINTED_BELOW", revision).encode(),
        path_in_repo="README.md",
        repo_id=args.repo,
        commit_message="Pin the revision in the model card",
    )

    print(f"\n  published https://huggingface.co/{args.repo}")
    print("\n  paste this into .env:\n")
    for line in [
        "DRONE_DETECTOR_ENABLED=true",
        f"DRONE_DETECTOR_REPO={args.repo}",
        f"DRONE_DETECTOR_REVISION={revision}",
        f"DRONE_DETECTOR_FILE={weights_name}",
        f"DRONE_DETECTOR_SHA256={digest}",
    ]:
        print(f"  {line}")

    RESULTS.mkdir(exist_ok=True)
    out = RESULTS / f"published_{args.repo.split('/')[-1]}.json"
    out.write_text(
        json.dumps(
            {
                "published_at": datetime.now(UTC).isoformat(timespec="seconds"),
                "repo": args.repo,
                "revision": revision,
                "sha256": digest,
                "file": weights_name,
                "classes": list(DMD_CLASSES),
                "checkpoint": info,
                "private": args.private,
            },
            indent=2,
        )
        + "\n"
    )
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
